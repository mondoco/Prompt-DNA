/**
* Turn a URL match into a link.
*
* @type {ReplaceFunction}
* @param {string} _
*   Whole match.
* @param {string} protocol
*   Protocol (`http://`, `https://`) or `www`.
* @param {string} domain
*   Host name, up to the path.
* @param {string} path
*   Path, query, and fragment.
* @param {RegExpMatchObject} match
*   Match object.
* @returns {Array<PhrasingContent> | Link | false}
*   Link, link and trailing text, or `false` if not a URL.
*/
function findUrl(_, protocol, domain, path, match) {
	if (!previous(match)) return false;
	let prefix = "";
	if (/^w/i.test(protocol)) {
		domain = protocol + domain;
		protocol = "";
		prefix = "http://";
	}
	if (unicodePunctuation(domain.charCodeAt(0)) || !isCorrectDomain(domain)) return false;
	const parts = splitUrl(domain + path);
	/** @type {Link} */
	const result = {
		type: "link",
		title: null,
		url: prefix + protocol + parts[0],
		children: [{
			type: "text",
			value: protocol + parts[0],
			position: void 0
		}],
		position: void 0
	};
	if (parts[1]) return [result, {
		type: "text",
		value: parts[1],
		position: void 0
	}];
	return result;
}
